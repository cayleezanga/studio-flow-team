-- Master data: one row per member, instructor, type of class, or room.
CREATE TABLE members (
    member_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(25)
);

CREATE TABLE instructors (
    instructor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    specialty VARCHAR(100)
);

CREATE TABLE class_types (
    class_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    difficulty_level VARCHAR(20) NOT NULL
        CHECK (difficulty_level IN ('Beginner', 'Intermediate', 'Advanced')),
    price NUMERIC(8,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE rooms (
    room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name VARCHAR(80) NOT NULL UNIQUE,
    max_capacity INTEGER NOT NULL CHECK (max_capacity > 0)
);

-- Scheduled classes: each session uses one type, instructor, and room.
CREATE TABLE class_sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_type_id INTEGER NOT NULL REFERENCES class_types(class_type_id),
    instructor_id INTEGER NOT NULL REFERENCES instructors(instructor_id),
    room_id INTEGER NOT NULL REFERENCES rooms(room_id),
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    UNIQUE (room_id, session_date, start_time),
    UNIQUE (instructor_id, session_date, start_time)
);

-- Bookings: one row per member and class session.
-- Cancel an existing reservation by changing its status, not by adding a duplicate.
CREATE TABLE reservations (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES members(member_id),
    session_id INTEGER NOT NULL REFERENCES class_sessions(session_id),
    booking_date DATE NOT NULL DEFAULT CURRENT_DATE,
    booking_status VARCHAR(20) NOT NULL DEFAULT 'Booked'
        CHECK (booking_status IN ('Booked', 'Cancelled', 'Attended')),
    UNIQUE (member_id, session_id)
);

-- Payment RECORDS only: no real credit card or bank processing.
-- At most one payment record per reservation.
CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id INTEGER NOT NULL UNIQUE REFERENCES reservations(reservation_id),
    amount NUMERIC(8,2) NOT NULL CHECK (amount >= 0),
    payment_date DATE,
    payment_method VARCHAR(20)
        CHECK (payment_method IN ('Card', 'Cash', 'Other')),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (payment_status IN ('Pending', 'Paid', 'Refunded'))
);

-- Later application rules (not enforced by these simple table constraints):
-- 1. session capacity cannot exceed rooms.max_capacity.
-- 2. stop new bookings once active reservations reach session capacity.
-- 3. protect bookings from concurrent overbooking inside a transaction.
-- 4. deletion of a reservation with a payment requires an explicit policy;
--    the default FK protects existing payment history from accidental deletion.
